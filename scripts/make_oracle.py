"""Build a deliberately overfit strategy: round1's whole future mid path is pasted into the file.

usage: uv run python scripts/make_oracle.py data/round1_train.csv strategies/round1/oracle_overfit_round1.py [H_US EDGE EDGE_TAKE K_INV SWEEP]
SWEEP 1: when crossing, bid up to floor(fair - EDGE_TAKE) instead of only the best price (takes deep levels on jumps).
The strategy quotes around fair = the mid H_US microseconds in the future (looked up in the table),
using the same quoting/ladder/risk logic as strategies/round1/imbalance_mm.py.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path.cwd()))
from analysis.context import GRID_STEP_US  # noqa: E402
from analysis.replay import replay  # noqa: E402
from analysis.tape import load_tape  # noqa: E402

tape_path, out = Path(sys.argv[1]), Path(sys.argv[2])
h_us, edge, edge_take, k_inv, sweep = (sys.argv[3:8] + ['350000', '0.3', '0.25', '0.002', '0'][len(sys.argv[3:8]):])

rp = replay(load_tape(tape_path), GRID_STEP_US)
ok = np.isfinite(rp.best_bid) & np.isfinite(rp.best_ask)
ts = rp.ev_ts[ok]
m2 = (rp.best_bid[ok] + rp.best_ask[ok]).astype(np.int64)  # 2 * mid, an integer
keep = np.r_[True, m2[1:] != m2[:-1]]
ts, m2 = ts[keep], m2[keep]
dts = np.diff(np.r_[0, ts])


def lst(a):
    return '[' + ','.join(map(str, a.tolist())) + ']'


src = f'''"""DUMMY ORACLE: knows {tape_path.stem}'s future mid. Only meaningful on {tape_path}. Never submit.

Generated by scripts/make_oracle.py. fair = mid H_US in the future; quoting as in imbalance_mm.py.
"""
from __future__ import annotations

from simulator.models import OrderBookSnapshot, OrderRequest, OrderStatus, OrderType, PrivateOrderEvent, Side, Trade
from simulator.strategy import BaseStrategy

H_US = {h_us}
EDGE = {edge}
EDGE_TAKE = {edge_take}
K_INV = {k_inv}
SWEEP = {sweep}
QTY = 200
MAX_POS = 100
KEEP_LEVELS = 1
MIN_NEW = 10

# time deltas (us) and 2*mid at every mid change of the market-only book
DT = {lst(dts)}
M2 = {lst(m2)}


class OracleMM(BaseStrategy):
    def __init__(self) -> None:
        super().__init__()
        t = 0
        self.t = []
        for d in DT:
            t += d
            self.t.append(t)
        self.k = 0
        self.inv = 0
        self.orders: dict[str, list] = {{}}
        self.cancel_sent: set[str] = set()

    def _future_mid(self, now: int) -> float:
        target = now + H_US
        t = self.t
        k = self.k
        while k + 1 < len(t) and t[k + 1] <= target:
            k += 1
        self.k = k
        return M2[k] / 2

    def _cancel(self, oid: str) -> None:
        if oid not in self.cancel_sent:
            self.cancel_order(oid)
            self.cancel_sent.add(oid)

    def on_order_book_change(self, snapshot: OrderBookSnapshot, trades: list[Trade]) -> None:
        bb = ba = None
        for o in snapshot.bids:
            if o.owner == 'market':
                bb = o.price
                break
        for o in snapshot.asks:
            if o.owner == 'market':
                ba = o.price
                break
        if bb is None or ba is None:
            return
        fair = self._future_mid(snapshot.timestamp_us) - K_INV * self.inv
        if fair - ba >= EDGE_TAKE:
            pb = int(fair - EDGE_TAKE) if SWEEP else ba
        else:
            pb = bb
            while fair - pb < EDGE:
                pb -= 1
        if bb - fair >= EDGE_TAKE:
            pa = -int(-(fair + EDGE_TAKE)) if SWEEP else bb
        else:
            pa = ba
            while pa - fair < EDGE:
                pa += 1
        self._side(1, pb)
        self._side(-1, pa)

    def _side(self, sign: int, target: int) -> None:
        resting = 0
        at_target = 0
        keep = []
        for oid, o in self.orders.items():
            if o[0] != sign:
                continue
            resting += o[2]
            if oid in self.cancel_sent:
                continue
            behind = (target - o[1]) * sign
            if behind < 0 or behind > KEEP_LEVELS:
                self._cancel(oid)
            elif behind == 0:
                at_target += o[2]
            else:
                keep.append((behind, oid))
        if at_target >= QTY:
            return
        room = MAX_POS - sign * self.inv - resting
        want = QTY - at_target
        if room < min(want, MIN_NEW) and keep:
            keep.sort(reverse=True)
            self._cancel(keep[0][1])
            return
        q = min(want, room)
        if q < MIN_NEW:
            return
        side = Side.BUY if sign > 0 else Side.SELL
        oid = self.send_order(OrderRequest(side=side, price=target, quantity=q, order_type=OrderType.LIMIT))
        self.orders[oid] = [sign, target, q]

    def on_private_order_update(self, event: PrivateOrderEvent) -> None:
        o = self.orders.get(event.order_id)
        if o is None:
            return
        st = event.status
        if st == OrderStatus.FILLED or st == OrderStatus.PARTIALLY_FILLED:
            self.inv += o[0] * event.filled_quantity
            o[2] = event.remaining_quantity
            if st == OrderStatus.FILLED:
                self._drop(event.order_id)
        elif st == OrderStatus.CANCELED or st == OrderStatus.REJECTED:
            self._drop(event.order_id)

    def _drop(self, oid: str) -> None:
        self.orders.pop(oid, None)
        self.cancel_sent.discard(oid)
'''
out.write_text(src)
print(f'{out}: {len(ts)} mid changes, {out.stat().st_size / 1e6:.2f} MB, H_US={h_us} EDGE={edge}')
